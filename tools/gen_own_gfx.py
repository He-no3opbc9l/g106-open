#!/usr/bin/env python3
"""Generate src/gfx_own.c: our own boot logo (48x48).

Drawn procedurally (ring + wave); the power-off screen is text in the UI fonts (radio.c);
no stock graphics. Output bitmaps: row-major, 1 bpp, MSB = leftmost pixel (see gfx_data.h).

usage: python3 -I tools/gen_own_gfx.py src/gfx_own.c
       python3 -I tools/gen_own_gfx.py --ascii     (print the bitmap)
"""
import math
import sys


class Bmp:
    def __init__(self, w, h):
        self.w, self.h = w, h
        self.p = [[0] * w for _ in range(h)]

    def on(self, x, y):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.p[y][x] = 1

    def packed(self):
        bpl = (self.w + 7) // 8
        out = bytearray(bpl * self.h)
        for y in range(self.h):
            for x in range(self.w):
                if self.p[y][x]:
                    out[y * bpl + x // 8] |= 0x80 >> (x % 8)
        return bpl, bytes(out)

    def ascii(self):
        return "\n".join("".join("#" if v else "." for v in r) for r in self.p)


def boot_logo():
    """48x48: ring with a sine wave through it (the caption is drawn as text under it)."""
    b = Bmp(48, 48)
    c = 23.5
    for y in range(48):
        for x in range(48):
            if 21.2 <= math.hypot(x - c, y - c) <= 23.8:
                b.on(x, y)
    curve = [(8 + 32 * i / 400.0, 23.5 + 7.0 * math.sin(i / 400.0 * 2 * math.pi * 2))
             for i in range(401)]
    for y in range(48):
        for x in range(48):
            if min(math.hypot(x + 0.5 - cx, y + 0.5 - cy) for cx, cy in curve) <= 1.15:
                b.on(x, y)
    return b


def main():
    imgs = {"img_boot": boot_logo()}
    if sys.argv[1] == "--ascii":
        for n, b in imgs.items():
            print(f"== {n}\n{b.ascii()}")
        return
    o = ["/* GENERATED by tools/gen_own_gfx.py (original artwork). Do not edit by hand. */",
         '#include "gfx_data.h"', ""]
    for n, b in imgs.items():
        bpl, data = b.packed()
        body = ", ".join(f"0x{v:02X}" for v in data)
        o.append(f"static const uint8_t {n}_bits[] = {{{body}}};")
        o.append(f"const gfx_bitmap_t {n} = {{{b.w}, {b.h}, {bpl}, {n}_bits}};")
        o.append("")
    open(sys.argv[1], "w").write("\n".join(o))


if __name__ == "__main__":
    main()
